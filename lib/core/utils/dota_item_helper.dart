      if (_itemAliases.containsKey(nameFromId)) {
        final target = _itemAliases[nameFromId]!;
        if (_knownItems.contains(target)) {
          return '$itemsDirectory/$target.png';
        }
      }
    }

    // 2. Se tiver nome em string
    if (itemName != null && itemName.trim().isNotEmpty) {
      final clean = normalizeItemName(itemName);
      if (clean.isEmpty || clean == 'empty') return null;

      // 2a. Verifica se é exatamente um item conhecido
      if (_knownItems.contains(clean)) {
        return '$itemsDirectory/$clean.png';
      }

      // 2b. Consulta o dicionário de aliases
      if (_itemAliases.containsKey(clean)) {
        final target = _itemAliases[clean]!;
        if (_knownItems.contains(target)) {
          return '$itemsDirectory/$target.png';
        }
      }

      // 2c. Normalização sem underscores (ex: "powertreads" -> "power_treads")
